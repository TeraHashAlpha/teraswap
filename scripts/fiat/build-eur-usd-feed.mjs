#!/usr/bin/env node
/**
 * [feat/ui-v2-fiat-value] Generates src/config/eur-usd-feed.json: the Chainlink EUR / USD feed the v2 euro display reads.
 *
 * The address is NEVER typed by hand. It is taken from Chainlink's own reference-data directory (the canonical ENS-named
 * entry `eur-usd`, NOT the `-shared-svr` sibling) and then confirmed on-chain against TWO independent RPCs: description()
 * must be "EUR / USD", decimals() must be 8, latestRoundData() must carry a positive answer. Any disagreement exits non-zero
 * and writes nothing.
 *
 *   node scripts/fiat/build-eur-usd-feed.mjs            # write the file
 *   node scripts/fiat/build-eur-usd-feed.mjs --check    # exit 1 when the file differs from what the directory says
 *
 * Needs network. Override the RPCs with EUR_FEED_RPC_A / EUR_FEED_RPC_B (names only are read here, never printed).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createPublicClient, getAddress, http, parseAbi } from 'viem'
import { mainnet } from 'viem/chains'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'src', 'config', 'eur-usd-feed.json')
const DIRECTORY = 'https://reference-data-directory.vercel.app/feeds-mainnet.json'
const RPCS = [process.env.EUR_FEED_RPC_A || 'https://ethereum-rpc.publicnode.com', process.env.EUR_FEED_RPC_B || 'https://eth.drpc.org']
const ABI = parseAbi([
  'function description() view returns (string)',
  'function decimals() view returns (uint8)',
  'function latestRoundData() view returns (uint80 roundId, int256 answer, uint256 startedAt, uint256 updatedAt, uint80 answeredInRound)',
])

const res = await fetch(DIRECTORY)
if (!res.ok) throw new Error(`directory fetch failed: ${res.status}`)
const entries = (await res.json()).filter((e) => e.ens === 'eur-usd' && e.path === 'eur-usd')
if (entries.length !== 1) throw new Error(`expected exactly one canonical eur-usd entry, found ${entries.length}`)
const [entry] = entries
const feed = getAddress(entry.proxyAddress)
if (typeof entry.heartbeat !== 'number' || entry.heartbeat <= 0) throw new Error('directory entry has no heartbeat')

for (const url of RPCS) {
  const client = createPublicClient({ chain: mainnet, transport: http(url) })
  const [description, decimals, round] = await Promise.all([
    client.readContract({ address: feed, abi: ABI, functionName: 'description' }),
    client.readContract({ address: feed, abi: ABI, functionName: 'decimals' }),
    client.readContract({ address: feed, abi: ABI, functionName: 'latestRoundData' }),
  ])
  if (description !== 'EUR / USD') throw new Error(`description() is ${JSON.stringify(description)} on ${new URL(url).host}`)
  if (decimals !== 8) throw new Error(`decimals() is ${decimals} on ${new URL(url).host}`)
  if (round[1] <= 0n) throw new Error(`non-positive answer on ${new URL(url).host}`)
}

const next = {
  $comment:
    'Generated by scripts/fiat/build-eur-usd-feed.mjs from the Chainlink reference-data directory (canonical ENS entry eur-usd) and confirmed on-chain on two RPCs. Do not edit by hand. maxStaleness = heartbeat + 3600 s, the same convention as dca-feed-registrations.json. DISPLAY ONLY: the euro figure feeds no gate, minimum, tier, consent, calldata or signature.',
  source: 'chainlink-directory feeds-mainnet.json path=eur-usd ens=eur-usd',
  chains: {
    1: {
      feed,
      description: 'EUR / USD',
      decimals: 8,
      heartbeat: entry.heartbeat,
      maxStaleness: entry.heartbeat + 3600,
    },
  },
}
const text = `${JSON.stringify(next, null, 2)}\n`
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    /* missing file counts as a difference */
  }
  if (current !== text) {
    console.error('src/config/eur-usd-feed.json differs from the directory')
    process.exit(1)
  }
  console.log('eur-usd-feed.json matches the directory and the chain')
} else {
  writeFileSync(OUT, text)
  console.log(`wrote ${OUT} (chain 1 feed ${feed}, heartbeat ${entry.heartbeat})`)
}
