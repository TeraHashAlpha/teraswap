#!/usr/bin/env node
/**
 * [CHORE-P0-RESCUE-AUDIT-REPORTS] Auto-commit + push cadence audit reports.
 *
 * Why this exists: the health-report generators (owner-level Claude scheduled
 * tasks in ~/.claude/scheduled-tasks/teraswap-*) write Daily/Weekly/Monthly/
 * Quarterly reports into the local working copy with NO commit/push step. The
 * working copy sat on a dead branch for weeks, so 28 reports existed only on
 * one disk (P0 of AZ-REVIEW-2026-07-06, rescued in this PR). This script makes
 * a report durable the moment it is written: each run commits any new/modified
 * cadence report to the dedicated tracked branch `audits/cadence` and pushes —
 * WITHOUT touching the operator's checked-out branch (temp detached worktree).
 *
 * [CHORE-DAILY-HEALTH-REPORT-GHA] The DAILY health report specifically no longer depends on this
 * script: `.github/workflows/daily-health-report.yml` now generates AND persists it end to end on
 * a schedule, on GitHub's infrastructure, so it needs no local SSH signing key (the recurring
 * failure this whole script exists to route around — see any Audits/Daily/health-*.md before that
 * workflow shipped for the "fatal: either user.signingkey..." error every sandboxed run hit) and
 * checks PRODUCTION directly rather than a sandbox's unset local env vars. This script remains the
 * PRIMARY persistence path for Weekly/Monthly/Quarterly reports (not yet moved to a scheduled
 * Action) and stays available for a manually-run or ad hoc Daily report.
 *
 * Usage (appended to each generator SKILL.md as its final step):
 *   node scripts/commit-audit-report.mjs
 *
 * Guarantees / safety:
 *   - Scopes to Audits/{Daily,Weekly,Monthly,Quarterly}/*.md ONLY — never
 *     sweeps unrelated untracked files.
 *   - Never switches the operator's branch, never stashes, never force-pushes.
 *   - Commits inherit the repo-local identity + SSH signing config (noreply
 *     committer, commit.gpgsign=true — rule #12).
 *   - Branch base: existing origin/audits/cadence tip, else origin/main.
 *   - Exit 0 with a message when there is nothing new (idempotent).
 */
import { execFileSync } from 'node:child_process'
import { cpSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// [FIX-AUDIT-CROSS-LANE-GUARD] Two producers can write the same Audits/Daily path — this
// script's cadence generators vs. the daily-health-report GitHub Action. Refuse to let a
// same-path write silently clobber a report the Action produced, identified by its own
// "Generated by the `daily-health-report` GitHub Action" line — the way the 2026-08-03 local
// run did. Exported so it can be exercised by a harness without touching the network.
export function findCrossLaneConflicts(files, readRemoteContent, readLocalContent) {
  const MARKER = 'daily-health-report` GitHub Action'
  const conflicts = []
  for (const f of files) {
    const remote = readRemoteContent(f)
    if (remote === null) continue // not on the branch yet — nothing to protect
    if (!remote.includes(MARKER)) continue // not GHA-authored — same-lane overwrite is fine
    const local = readLocalContent(f)
    if (remote === local) continue // identical content — nothing would actually change
    conflicts.push(f)
  }
  return conflicts
}

// AUDIT_REPO_DIR lets a scheduled task target a specific checkout explicitly;
// default is the repo containing this script.
const REPO = process.env.AUDIT_REPO_DIR
  ? resolve(process.env.AUDIT_REPO_DIR)
  : resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CADENCE_DIRS = ['Audits/Daily', 'Audits/Weekly', 'Audits/Monthly', 'Audits/Quarterly']
const BRANCH = 'audits/cadence'

// trimEnd, not trim: `git status --porcelain` lines that are worktree-modified-only (" M path")
// start with a leading space that IS the index-status column — a blanket .trim() strips it off
// the first line of the output, shifting every column and corrupting the slice(3) parse below
// the moment a modified (not untracked) report is first/only in the list.
const git = (args, cwd = REPO) =>
  execFileSync('git', ['-C', cwd, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trimEnd()

// Wrapped in main() + the import.meta.url guard below so this module can be `import()`-ed (e.g.
// to exercise findCrossLaneConflicts in isolation) without shelling out to git or exiting the host.
function main() {
  // 1. Enumerate new/modified/added cadence reports in the operator's working copy.
  //    --porcelain: "?? path" (untracked) / " M path" / "MM path" (modified) / "A  path" (added).
  //    XY is always exactly 2 chars + 1 separating space, so slice(3) is safe for all of those —
  //    EXCEPT rename lines ("R  old -> new"), which git emits once two reports (e.g. yesterday's
  //    and today's cadence report) are similar enough to trip rename detection; slice(3) would
  //    then return the literal "old -> new" as a single bogus path and cpSync() would ENOENT on
  //    it. --no-renames forces every touched path to report as its own plain XY-path line.
  const status = git(['status', '--porcelain', '--no-renames', '--', ...CADENCE_DIRS])
  const files = status
    .split('\n')
    .filter(Boolean)
    .map((l) => l.slice(3).trim())
    .filter((f) => f.endsWith('.md'))

  if (files.length === 0) {
    console.log('[commit-audit-report] nothing to persist — no new/modified Audits cadence reports.')
    return 0 // no worktree created yet — nothing to clean up
  }
  console.log(`[commit-audit-report] ${files.length} report(s) to persist:\n  ${files.join('\n  ')}`)

  // 2. Base the dedicated branch on its remote tip (or origin/main on first run).
  git(['fetch', 'origin', 'main'])
  let base = `origin/${BRANCH}`
  try {
    git(['fetch', 'origin', BRANCH])
    git(['rev-parse', '--verify', base])
  } catch {
    base = 'origin/main'
  }

  // 3. Temp detached worktree → copy reports in → signed commit → push.
  //
  // [FIX-AUDIT-WORKTREE-CLEANUP] Every exit below this point sets `exitCode` and falls through to
  // `finally` rather than calling the process's immediate-exit method directly — that method
  // terminates the process at once without running pending finally blocks, which is exactly how
  // ~28 worktrees under this prefix were orphaned (an immediate exit inside this try, past
  // `worktree add`, on every early-return run). Returning normally lets `finally` run every time,
  // and lets the caller set `process.exitCode` (below) instead of forcing an exit — see
  // [FIX-AUDIT-SILENT-EXIT] for why that distinction also matters for stdout that's still
  // buffered when the process would otherwise exit.
  const tmp = mkdtempSync(join(tmpdir(), 'audit-cadence-'))
  let exitCode = 0
  try {
    git(['worktree', 'add', '--detach', tmp, base])

    const conflicts = findCrossLaneConflicts(
      files,
      (f) => {
        try {
          return git(['show', `HEAD:${f}`], tmp)
        } catch {
          return null
        }
      },
      (f) => readFileSync(join(REPO, f), 'utf8'),
    )
    if (conflicts.length > 0) {
      console.error(
        `[commit-audit-report] ABORT: the following report(s) already exist on origin/${BRANCH} as ` +
          `GitHub Action output and this run would overwrite them — refusing to commit:\n  ${conflicts.join('\n  ')}`,
      )
      exitCode = 1
    } else {
      for (const f of files) {
        mkdirSync(join(tmp, dirname(f)), { recursive: true })
        cpSync(join(REPO, f), join(tmp, f), { preserveTimestamps: true })
      }
      git(['add', '--', ...CADENCE_DIRS], tmp)
      // Anything staged? (report may already be on the branch from a prior run)
      const staged = git(['diff', '--cached', '--name-only'], tmp).split('\n').filter(Boolean)
      if (staged.length === 0) {
        console.log('[commit-audit-report] nothing to persist — all reports already on the branch.')
      } else {
        const names = staged.map((f) => f.split('/').pop())
        const summary =
          names.length <= 6 ? names.join(', ') : `${names.slice(0, 6).join(', ')} +${names.length - 6} more`
        git(['commit', '-m', `docs(audits): cadence report(s) ${summary} [auto]`], tmp)
        git(['push', 'origin', `HEAD:refs/heads/${BRANCH}`], tmp)
        console.log(`[commit-audit-report] pushed ${staged.length} file(s) to origin/${BRANCH}.`)
      }
    }
  } finally {
    try {
      git(['worktree', 'remove', '--force', tmp])
    } catch {
      rmSync(tmp, { recursive: true, force: true })
    }
    try {
      git(['worktree', 'prune'])
    } catch {
      // best-effort — a failed prune here must not mask the run's real exitCode
    }
  }
  return exitCode
}

// realpathSync, not a raw string compare: on macOS /tmp is a symlink to /private/tmp, so
// import.meta.url (always the realpath) would silently never match a bare process.argv[1] and
// main() would never run — this was caught by a dry run through a /tmp sandbox during review.
const isMain = (() => {
  try {
    return process.argv[1] !== undefined && import.meta.url === `file://${realpathSync(process.argv[1])}`
  } catch {
    return false
  }
})()
// [FIX-AUDIT-SILENT-EXIT] Calling the process's immediate-exit method truncates buffered-but-not
// -yet-flushed stdout/stderr writes (e.g. when this process's output is piped, as it is under a
// scheduled task or GHA runner) — the exact shape of the 2026-08-04 failure: exit 0, zero stdout,
// nothing pushed, no error anywhere. Setting `process.exitCode` and letting the script return
// naturally lets Node drain its output streams before the process actually exits. The try/catch
// below is the backstop for errors main() doesn't already handle (e.g. a failing `git fetch`/`git
// push`) — every path out of this script now either logs its own outcome or lands here and logs
// the error; none exit silently.
if (isMain) {
  try {
    process.exitCode = main()
  } catch (err) {
    console.error(`[commit-audit-report] FATAL: ${err.message}`)
    process.exitCode = 1
  }
}
