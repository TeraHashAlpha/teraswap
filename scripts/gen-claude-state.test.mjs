// Runs the real script as a subprocess against a scratch repo, so the generated block, --write and --check
// are exercised end to end: fixture → expected block, and a changed deployments row → --check fails.
import { execFileSync } from 'node:child_process'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, copyFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, it, expect, afterEach } from 'vitest'

const SCRIPT_SRC = fileURLToPath(new URL('./gen-claude-state.mjs', import.meta.url))

const ADDR_A = '0x1111111111111111111111111111111111111111'
const ADDR_B = '0x2222222222222222222222222222222222222222'
const ADDR_C = '0x3333333333333333333333333333333333333333'

const DEPLOYMENTS = (addrB = ADDR_B) => `# Fixture deployments

## Contracts

| Role | Chain | Address | Verified facts |
|------|-------|---------|----------------|
| **FeeCollector V2** (instant swaps) | Ethereum Mainnet (1) | \`${ADDR_A}\` | 5,419 B · has swap fns |
| ⚠️ **OrderExecutor V3** (conditional orders) | Arbitrum One (42161) | \`${addrB}\` | **Deployed** · NOT operational |

### Key gotcha
| not | a | contract row |
`

const CLAUDE = (block) => `# Fixture CLAUDE.md

Intro paragraph that must survive a rewrite.

${block}

Trailing paragraph that must survive a rewrite.
`

const EXPECTED_BLOCK = `<!-- state:begin -->
<!-- Generated by scripts/gen-claude-state.mjs from repo content only (no date, no sha). Do not edit by hand:
     node scripts/gen-claude-state.mjs --write && node scripts/check-agents-parity.mjs --write -->

**Contracts** — copied from the "Contracts" table of \`docs/DEPLOYMENTS.md\`. One address can be a different contract on another chain:
always qualify by chain. Operational status and the checks behind each row are in that file's "Verified facts" column.

| Role | Chain | Address |
|------|-------|---------|
| FeeCollector V2 (instant swaps) | Ethereum Mainnet (1) | \`${ADDR_A}\` |
| OrderExecutor V3 (conditional orders) | Arbitrum One (42161) | \`${ADDR_B}\` |

**Workflows** (2, \`.github/workflows/\`): CI (\`ci.yml\`), Nightly sweep (\`nightly.yml\`)

**ADRs** (\`docs/ADR/\`): 3 files, ADR-001 to ADR-003; latest \`ADR-003-third\`, Status: Proposed

**Test suites** (no counts here, they change on every PR; \`node scripts/gen-claude-state.mjs --counts\` prints them): vitest, \`npx vitest run\`, config \`vitest.config.ts\` · keeper node:test, \`node --test\` in \`contracts/order-engine/executor/\` · Foundry, \`forge test\`, configs \`contracts/foundry.toml\`, \`contracts/order-engine/foundry.toml\`
<!-- state:end -->`

function put(root, rel, content) {
  const abs = path.join(root, rel)
  mkdirSync(path.dirname(abs), { recursive: true })
  writeFileSync(abs, content)
}

function makeRepo({ deployments = DEPLOYMENTS(), claudeBlock = '<!-- state:begin -->\nSTALE\n<!-- state:end -->' } = {}) {
  const root = mkdtempSync(path.join(tmpdir(), 'gen-claude-state-'))
  mkdirSync(path.join(root, 'scripts'))
  copyFileSync(SCRIPT_SRC, path.join(root, 'scripts', 'gen-claude-state.mjs'))
  put(root, 'CLAUDE.md', CLAUDE(claudeBlock))
  put(root, 'docs/DEPLOYMENTS.md', deployments)
  put(root, '.github/workflows/ci.yml', '# comment\nname: "CI"\non: push\n')
  put(root, '.github/workflows/nightly.yml', 'name: Nightly sweep\non: push\n')
  put(root, 'docs/ADR/ADR-001-first.md', '# ADR-001\n\n- **Status:** Accepted\n')
  put(root, 'docs/ADR/ADR-002-second.md', '# ADR-002\n\n- **Status:** Accepted — 2026-01-01\n')
  put(root, 'docs/ADR/ADR-003-third.md', '# ADR-003\n\n- **Status:** Proposed (design gate; owner to decide)\n')
  // The include array is followed by a comment holding `]` and a `/**/` glob, as the real config has.
  put(
    root,
    'vitest.config.ts',
    "export default { test: { include: [\n  'src/**/*.test.ts',\n  // [TAG] a comment with a bracket\n  'scripts/*.test.mjs',\n], coverage: { include: ['nope/**'] } } }\n",
  )
  put(root, 'src/a.test.ts', '')
  put(root, 'src/sub/b.test.ts', '')
  put(root, 'src/helper.ts', '') // not a test
  put(root, 'scripts/x.test.mjs', '')
  put(root, 'scripts/sub/y.test.mjs', '') // not under the scripts/*.test.mjs glob
  put(root, 'contracts/order-engine/executor/k.test.mjs', '')
  put(root, 'contracts/order-engine/executor/j.test.mjs', '')
  put(root, 'contracts/order-engine/executor/node_modules/dep/z.test.mjs', '') // vendored
  put(root, 'contracts/order-engine/executor/package.json', '{}')
  put(root, 'contracts/foundry.toml', '[profile.default]\n')
  put(root, 'contracts/order-engine/foundry.toml', '[profile.default]\n')
  put(root, 'contracts/lib/forge-std/foundry.toml', '') // vendored
  put(root, 'contracts/test/Fee.t.sol', '')
  put(root, 'contracts/lib/forge-std/test/Vendored.t.sol', '') // vendored
  put(root, 'contracts/out/Built.t.sol', '') // build output
  return root
}

function run(root, args) {
  try {
    const stdout = execFileSync('node', ['scripts/gen-claude-state.mjs', ...args], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] })
    return { code: 0, stdout, stderr: '' }
  } catch (err) {
    return { code: err.status, stdout: err.stdout ?? '', stderr: err.stderr ?? '' }
  }
}

const sandboxes = []
const sandbox = (opts) => {
  const root = makeRepo(opts)
  sandboxes.push(root)
  return root
}
afterEach(() => {
  while (sandboxes.length) rmSync(sandboxes.pop(), { recursive: true, force: true })
})

describe('gen-claude-state', () => {
  it('fixture → expected block (--print)', () => {
    const result = run(sandbox(), ['--print'])
    expect(result.code).toBe(0)
    expect(result.stdout.trimEnd()).toBe(EXPECTED_BLOCK)
  })

  it('is deterministic: no date, no sha, same bytes twice', () => {
    const root = sandbox()
    const a = run(root, ['--print']).stdout
    const b = run(root, ['--print']).stdout
    expect(a).toBe(b)
    expect(a).not.toMatch(/\b20\d\d-\d\d-\d\d\b/)
    expect(a).not.toMatch(/\b[0-9a-f]{40}\b/)
  })

  it('--write rewrites only the block, then --check passes (positive control)', () => {
    const root = sandbox()
    expect(run(root, ['--check']).code).toBe(1) // the stale placeholder block
    const w = run(root, ['--write'])
    expect(w.code).toBe(0)
    expect(readFileSync(path.join(root, 'CLAUDE.md'), 'utf8')).toBe(CLAUDE(EXPECTED_BLOCK))
    const c = run(root, ['--check'])
    expect(c.code).toBe(0)
    expect(c.stdout).toContain('is current')
  })

  it('a changed deployments row makes --check fail (negative control)', () => {
    const root = sandbox({ claudeBlock: EXPECTED_BLOCK })
    expect(run(root, ['--check']).code).toBe(0)

    writeFileSync(path.join(root, 'docs/DEPLOYMENTS.md'), DEPLOYMENTS(ADDR_C))
    const result = run(root, ['--check'])

    expect(result.code).toBe(1)
    expect(result.stderr).toContain('out of date')
    expect(result.stderr).toContain(ADDR_C) // the generated side of the first difference
    expect(result.stderr).toContain('gen-claude-state.mjs --write')
  })

  it('a new ADR makes --check fail', () => {
    const root = sandbox({ claudeBlock: EXPECTED_BLOCK })
    expect(run(root, ['--check']).code).toBe(0)
    put(root, 'docs/ADR/ADR-004-fourth.md', '# ADR-004\n\n- **Status:** Accepted\n')
    expect(run(root, ['--check']).code).toBe(1)
    run(root, ['--write'])
    expect(run(root, ['--check']).code).toBe(0)
  })

  it('adding a test file of any kind does NOT change the block (the merge-conflict fix)', () => {
    const root = sandbox({ claudeBlock: EXPECTED_BLOCK })
    expect(run(root, ['--check']).code).toBe(0)
    put(root, 'src/c.test.ts', '')
    put(root, 'src/deep/d.test.tsx', '')
    put(root, 'scripts/z.test.mjs', '')
    put(root, 'contracts/order-engine/executor/m.test.mjs', '')
    put(root, 'contracts/test/Other.t.sol', '')
    const result = run(root, ['--check'])
    expect([result.code, result.stdout]).toEqual([0, expect.stringContaining('is current')])
    expect(run(root, ['--print']).stdout.trimEnd()).toBe(EXPECTED_BLOCK)
  })

  it('changing something the block still states does: a new Foundry project, a moved keeper dir, no vitest config', () => {
    const root = sandbox({ claudeBlock: EXPECTED_BLOCK })
    put(root, 'contracts/extra/foundry.toml', '')
    const r = run(root, ['--check'])
    expect(r.code).toBe(1)
    expect(r.stderr).toContain('contracts/extra/foundry.toml')

    const moved = sandbox({ claudeBlock: EXPECTED_BLOCK })
    rmSync(path.join(moved, 'contracts/order-engine/executor'), { recursive: true })
    expect(run(moved, ['--check']).stderr).toContain('contracts/order-engine/executor/package.json not found')

    const noCfg = sandbox({ claudeBlock: EXPECTED_BLOCK })
    rmSync(path.join(noCfg, 'vitest.config.ts'))
    expect(run(noCfg, ['--check']).code).toBe(1)
  })

  it('--counts prints the counts to stdout, touches nothing, and the block carries no digit-count line', () => {
    const root = sandbox({ claudeBlock: EXPECTED_BLOCK })
    const before = readFileSync(path.join(root, 'CLAUDE.md'), 'utf8')
    const c = run(root, ['--counts'])
    expect(c.code).toBe(0)
    expect(c.stdout.trim()).toBe('vitest 3 · keeper node:test 2 · Foundry 1')
    put(root, 'src/c.test.ts', '')
    expect(run(root, ['--counts']).stdout.trim()).toBe('vitest 4 · keeper node:test 2 · Foundry 1')
    expect(readFileSync(path.join(root, 'CLAUDE.md'), 'utf8')).toBe(before)
    expect(EXPECTED_BLOCK).not.toMatch(/(?:vitest|node:test|Foundry) \d+/)
  })

  it('fails closed: missing markers, missing Contracts table, empty table', () => {
    const noMarkers = run(sandbox({ claudeBlock: 'no markers here' }), ['--check'])
    expect([noMarkers.code, noMarkers.stderr]).toEqual([1, expect.stringContaining('state:begin')])
    const noHeading = run(sandbox({ deployments: '# nothing\n' }), ['--check'])
    expect([noHeading.code, noHeading.stderr]).toEqual([1, expect.stringContaining('no "## Contracts" heading')])
    const noRows = run(sandbox({ deployments: '## Contracts\n\n| Role | Chain | Address |\n|---|---|---|\n' }), ['--check'])
    expect([noRows.code, noRows.stderr]).toEqual([1, expect.stringContaining('has no rows')])
  })

  it('needs exactly one mode flag', () => {
    expect(run(sandbox(), []).code).toBe(1)
    expect(run(sandbox(), ['--check', '--write']).code).toBe(1)
    expect(run(sandbox(), ['--counts', '--print']).code).toBe(1)
  })
})
